# ============================================================
# database.py — Connection to Supabase PostgreSQL
# connection string -> engine -> session -> models
# ============================================================

import uuid                                  # Python's UUID type, matches Postgres uuid columns
from datetime import datetime                # for timestamptz columns
from decimal import Decimal                  # exact numbers for money (never use float for money)
from typing import Optional                  # marks columns that may be empty (NULL)

from sqlalchemy import DateTime, ForeignKey, Numeric, String, create_engine, text
from sqlalchemy.dialects.postgresql import UUID                       # Postgres-specific uuid type
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, sessionmaker

from app import config                       # DATABASE_URL comes from .env

# ---------- Engine: the connection manager (one for the whole app) ----------
engine = create_engine(
    config.DATABASE_URL,                     # where the database is and how to log in
    pool_pre_ping=True,                      # test a connection before using it (Supabase closes idle ones)
)

# ---------- Session factory: makes one "conversation" per request ----------
SessionLocal = sessionmaker(
    bind=engine,                             # sessions borrow connections from our engine
    autoflush=False,                         # only send changes to the DB when we say so
    expire_on_commit=False,                  # keep objects readable after saving
)


# ---------- Base: every model inherits from this ----------
class Base(DeclarativeBase):
    pass                                     # empty on purpose; it just links models to SQLAlchemy


# ---------- Model: app_users table ----------
class AppUser(Base):
    __tablename__ = "app_users"              # the exact table name in Supabase

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )                                        # unique ID, generated by the database
    username: Mapped[str] = mapped_column(String(30), unique=True)        # login name, unique
    hashed_password: Mapped[str] = mapped_column(String(100))             # bcrypt hash only
    role: Mapped[str] = mapped_column(String(10), server_default="user")  # 'user' or 'admin'
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("now()")
    )                                        # set by the database at insert time


# ---------- Model: transactions table (your existing ledger) ----------
class Transaction(Base):
    __tablename__ = "transactions"           # your existing table

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)  # existing uuid key
    reference: Mapped[str] = mapped_column(String)                     # e.g. "TXN-0001"
    amount: Mapped[Decimal] = mapped_column(Numeric)                   # money, exact
    currency: Mapped[str] = mapped_column(String)                      # Postgres enum, read as text
    direction: Mapped[str] = mapped_column(String)                     # Postgres enum, read as text
    status: Mapped[str] = mapped_column(String)                        # Postgres enum, read as text
    merchant: Mapped[str] = mapped_column(String)                      # who was paid / who paid
    description: Mapped[Optional[str]] = mapped_column(String)         # may be empty
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))  # when created
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))  # last change
    owner_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True), ForeignKey("app_users.id")
    )                                        # the new column: which user owns this transaction


# ---------- Model: revoked_tokens table (used in Phase 11) ----------
class RevokedToken(Base):
    __tablename__ = "revoked_tokens"         # refresh tokens that can't be used any more

    jti: Mapped[str] = mapped_column(String(64), primary_key=True)    # the token's unique ID
    revoked_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("now()")
    )                                        # when it was revoked


# ---------- Dependency: one session per API request ----------
def get_db():
    """Open a session for a request, and always close it afterwards."""
    db = SessionLocal()                      # start the conversation
    try:
        yield db                             # hand it to the endpoint; pause here while it runs
    finally:
        db.close()                           # endpoint finished (or crashed): return the connection